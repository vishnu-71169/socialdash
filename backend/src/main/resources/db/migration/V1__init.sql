-- SocialDash initial schema. All timestamps are stored in UTC.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'USER',
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE social_accounts (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    platform               VARCHAR(20)  NOT NULL,
    platform_account_id    VARCHAR(255) NOT NULL,
    handle                 VARCHAR(100) NOT NULL,
    display_name           VARCHAR(150) NOT NULL,
    simulated              BOOLEAN      NOT NULL,
    -- AES-GCM encrypted; never returned to the client
    access_token_encrypted TEXT,
    token_expires_at       TIMESTAMP WITH TIME ZONE,
    connected_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    last_synced_at         TIMESTAMP WITH TIME ZONE,
    engagements_synced_at  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_social_account UNIQUE (user_id, platform, platform_account_id)
);
CREATE INDEX idx_social_accounts_user ON social_accounts (user_id);

-- One row per piece of content. Per-platform delivery lives in post_publications.
CREATE TABLE posts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    content      TEXT        NOT NULL,
    media_url    VARCHAR(1000),
    status       VARCHAR(20) NOT NULL,
    scheduled_at TIMESTAMP WITH TIME ZONE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    version      BIGINT      NOT NULL DEFAULT 0
);
CREATE INDEX idx_posts_user_status ON posts (user_id, status);
CREATE INDEX idx_posts_user_scheduled ON posts (user_id, scheduled_at);

-- Each publication succeeds or fails independently of the others for the same post.
CREATE TABLE post_publications (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id            BIGINT      NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    social_account_id  BIGINT      NOT NULL REFERENCES social_accounts (id) ON DELETE CASCADE,
    status             VARCHAR(20) NOT NULL,
    attempt_count      INT         NOT NULL DEFAULT 0,
    next_attempt_at    TIMESTAMP WITH TIME ZONE,
    claimed_at         TIMESTAMP WITH TIME ZONE,
    published_at       TIMESTAMP WITH TIME ZONE,
    external_post_id   VARCHAR(255),
    external_url       VARCHAR(1000),
    last_error         VARCHAR(1000),
    -- latest metrics, denormalised for cheap sorting; history is in post_analytics
    impressions        BIGINT      NOT NULL DEFAULT 0,
    likes              BIGINT      NOT NULL DEFAULT 0,
    comments           BIGINT      NOT NULL DEFAULT 0,
    shares             BIGINT      NOT NULL DEFAULT 0,
    metrics_updated_at TIMESTAMP WITH TIME ZONE,
    version            BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uq_post_publication UNIQUE (post_id, social_account_id)
);
CREATE INDEX idx_publications_due ON post_publications (status, next_attempt_at);
CREATE INDEX idx_publications_account_published ON post_publications (social_account_id, published_at);

-- Daily account metrics. Today's row is updated in place as the day progresses.
CREATE TABLE analytics_snapshots (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    social_account_id BIGINT NOT NULL REFERENCES social_accounts (id) ON DELETE CASCADE,
    snapshot_date     DATE   NOT NULL,
    recorded_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    followers         BIGINT NOT NULL,
    impressions       BIGINT NOT NULL,
    likes             BIGINT NOT NULL,
    comments          BIGINT NOT NULL,
    shares            BIGINT NOT NULL,
    CONSTRAINT uq_snapshot_account_date UNIQUE (social_account_id, snapshot_date)
);

CREATE TABLE post_analytics (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_publication_id BIGINT NOT NULL REFERENCES post_publications (id) ON DELETE CASCADE,
    recorded_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    impressions         BIGINT NOT NULL,
    likes               BIGINT NOT NULL,
    comments            BIGINT NOT NULL,
    shares              BIGINT NOT NULL
);
CREATE INDEX idx_post_analytics_publication_time ON post_analytics (post_publication_id, recorded_at);

CREATE TABLE tracked_keywords (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    keyword         VARCHAR(100) NOT NULL,
    -- NULL means "all platforms"
    platform        VARCHAR(20),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    last_checked_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_tracked_keywords_user ON tracked_keywords (user_id);

CREATE TABLE social_mentions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracked_keyword_id BIGINT       NOT NULL REFERENCES tracked_keywords (id) ON DELETE CASCADE,
    platform           VARCHAR(20)  NOT NULL,
    external_id        VARCHAR(255) NOT NULL,
    author_handle      VARCHAR(100) NOT NULL,
    content            TEXT         NOT NULL,
    url                VARCHAR(1000),
    detected_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_mention UNIQUE (tracked_keyword_id, platform, external_id)
);
CREATE INDEX idx_mentions_keyword_time ON social_mentions (tracked_keyword_id, detected_at);

CREATE TABLE engagements (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    social_account_id BIGINT       NOT NULL REFERENCES social_accounts (id) ON DELETE CASCADE,
    external_id       VARCHAR(255) NOT NULL,
    type              VARCHAR(20)  NOT NULL,
    status            VARCHAR(20)  NOT NULL,
    author_name       VARCHAR(150) NOT NULL,
    author_handle     VARCHAR(100) NOT NULL,
    content           TEXT         NOT NULL,
    received_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    reply_content     TEXT,
    replied_at        TIMESTAMP WITH TIME ZONE,
    resolved_at       TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_engagement UNIQUE (social_account_id, external_id)
);
CREATE INDEX idx_engagements_account_status_time ON engagements (social_account_id, status, received_at);
